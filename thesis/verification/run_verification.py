#!/usr/bin/env python3
"""Run the verification suite and write the LaTeX table the thesis prints.

Usage:  python3 run_verification.py
Writes: verification_results.tex  (input by Appendix F)
        verification_results.json (machine-readable record)
"""
from __future__ import annotations
import json, platform, subprocess, sys, time, datetime, os, re, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
SUITES = {
    "test_axioms.py":      ("A", "Axioms, aggregation and the rival ontology"),
    "test_crf.py":         ("E", "Capability Realisation Function"),
    "test_dynamics.py":    ("B", "Dynamical layers: ODE, SDE, Fokker--Planck"),
    "test_haemophilia.py": ("C", "Factor kinetics, ITI and gene therapy"),
    "test_economics.py":   ("A, D", "Net benefit, budget impact and DALYs"),
    "test_prognostic.py":  ("3, 6", "Survival, competing risks and net benefit"),
    "test_measurement.py": ("5", "Reliability, validity and factor scores"),
    "test_chapter_examples.py": ("1, 7--9", "Worked examples in the chapters"),
}


def esc(s: str) -> str:
    return (s.replace("_", r"\_").replace("&", r"\&").replace("%", r"\%")
             .replace("#", r"\#"))


def _clear_bytecode() -> None:
    """Remove cached .pyc files before running.

    Python will load a stale __pycache__ entry in preference to an edited
    source file in some circumstances, and a suite that reports green from
    bytecode that no longer matches the source is worse than no suite. This
    ran green once against mutated bytecode during development; the guard
    exists because of that.
    """
    for root, dirs, files in os.walk(HERE):
        for d in list(dirs):
            if d == "__pycache__":
                shutil.rmtree(os.path.join(root, d), ignore_errors=True)
                dirs.remove(d)
        for f in files:
            if f.endswith(".pyc"):
                os.remove(os.path.join(root, f))


def main() -> int:
    _clear_bytecode()
    rows, total_pass, total_fail = [], 0, 0
    t0 = time.time()
    for fname, (appx, label) in SUITES.items():
        r = subprocess.run(
            [sys.executable, "-B", "-m", "pytest", f"tests/{fname}", "-q",
             "--no-header", "-p", "no:cacheprovider"],
            cwd=HERE, capture_output=True, text=True)
        out = r.stdout
        p = int(m.group(1)) if (m := re.search(r"(\d+) passed", out)) else 0
        f = int(m.group(1)) if (m := re.search(r"(\d+) failed", out)) else 0
        total_pass += p
        total_fail += f
        rows.append(dict(file=fname, appendix=appx, label=label,
                         passed=p, failed=f))
        print(f"{fname:24s} {p:3d} passed  {f:3d} failed")
    elapsed = time.time() - t0

    meta = dict(
        generated=datetime.datetime.now(datetime.timezone.utc)
                  .strftime("%Y-%m-%d %H:%M UTC"),
        python=platform.python_version(),
        platform=platform.platform(),
        seed="fixed per test; see the source",
        elapsed_s=round(elapsed, 1),
        passed=total_pass, failed=total_fail, rows=rows)

    with open(os.path.join(HERE, "verification_results.json"), "w") as fh:
        json.dump(meta, fh, indent=2)

    lines = [
        "% Generated by verification/run_verification.py. Do not edit by hand.",
        r"\begin{table}[htbp]\centering",
        r"\caption{Result of running the verification suite. Each test asserts a "
        r"numbered statement from the chapter or appendix named. The suite is "
        r"re-run and this table regenerated on every build of the thesis.}",
        r"\label{tab:verification}",
        r"\footnotesize",
        r"\begin{tabular}{p{4.6cm} p{1.6cm} p{5.4cm} r r}",
        r"\toprule",
        r"\textbf{Test module} & \textbf{Covers} & \textbf{Subject} & "
        r"\textbf{Passed} & \textbf{Failed} \\",
        r"\midrule",
    ]
    for row in rows:
        lines.append(
            f"\\texttt{{{esc(row['file'])}}} & {row['appendix']} & "
            f"{row['label']} & {row['passed']} & {row['failed']} \\\\")
    lines += [
        r"\midrule",
        rf"\textbf{{Total}} & & & \textbf{{{total_pass}}} & "
        rf"\textbf{{{total_fail}}} \\",
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
        rf"\noindent\emph{{Run {meta['generated']} on Python "
        rf"{meta['python']}, {esc(meta['platform'])}, in "
        rf"{meta['elapsed_s']}\,s.}}",
    ]
    with open(os.path.join(HERE, "verification_results.tex"), "w") as fh:
        fh.write("\n".join(lines) + "\n")

    print(f"\n{total_pass} passed, {total_fail} failed in {elapsed:.1f}s")
    return 1 if total_fail else 0


if __name__ == "__main__":
    sys.exit(main())
